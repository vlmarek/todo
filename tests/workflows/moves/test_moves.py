    def test_reconciliation_interrupt_retains_attributable_remote_outcome(self):
        for outcome, classification in (('ok', 'accepted'),
                ({'error_code': 1, 'error': 'Destination parent is unavailable'}, 'rejected'),
                (None, 'unknown')):
            for interrupt_at in (1, 2):  # Current read and subsequent freshness read.
                with self.subTest(outcome=classification, interrupt_at=interrupt_at):
                    workflow, http = self.workflow(self.after('D', 'P', 'cat'),
                        {'id':'D','parent_id':'P'}, outcome=outcome, interrupt_at=interrupt_at)
                    preflight = []
                    refresh = workflow.synchronizer.read_local
                    def remember():
                        result = refresh()
                        preflight.append({name: (self.root / name).read_bytes()
                            for name in ('cache.json', 'history.json', 'binding.json', 'report-cursor')})
                        return result
                    with patch.object(workflow.synchronizer, 'read_local', side_effect=remember):
                        with self.assertRaises(SyncInterrupted) as caught:
                            workflow.execute(['move','D','P'])
                    error = caught.exception.failure
                    self.assertEqual(error.remote_outcome, classification)
                    self.assertIn('interrupted', str(error))
                    if classification == 'rejected':
                        self.assertIn('Destination parent is unavailable', str(error))
                    self.assertIn('A > B > C > D', str(error))
                    self.assertIn('task P', str(error))
                    self.assertIn('do not replay', str(error))
                    self.assertIn('todo --refresh now', str(error))
                    for name, content in preflight[0].items():
                        self.assertEqual((self.root / name).read_bytes(), content)
                    with exclusive_lock('after reconciliation interrupt', self.root):
                        saved = Synchronizer(None, self.store).read_local().snapshot
                        self.assertEqual(saved.items['D'].parent_id, 'C')
                        self.assertEqual(d.instant_text(saved.items['E'].completed_at), DONE)
                        self.assertEqual(set(saved.comments), {'n'+r['id'] for r in self.rows})
                    self.assertEqual(len(http.requests), interrupt_at + 1)

    def test_unknown_and_rejected_stop_without_publication_or_replay(self):
        for outcome, classification in ((None,'unknown'), ({'error_code': 1,
                'error':'Destination parent is unavailable; secret\nAuthorization: Bearer other-token'},'rejected')):
            workflow, http = self.workflow(self.rows, {'id':'D','parent_id':'P'}, outcome=outcome)
            with patch.object(self.store, 'publish_snapshot', wraps=self.store.publish_snapshot) as pub:
                with self.assertRaises(MoveError) as caught: workflow.execute(['move','D','P'])
                self.assertEqual(caught.exception.remote_outcome, classification)
                message = str(caught.exception)
                self.assertIn('step A > B > C > D in cat', message)
                self.assertIn('task P in cat', message)
                if classification == 'rejected':
                    self.assertIn('Destination parent is unavailable', message)
                    self.assertNotIn('secret', message)
                    self.assertNotIn('other-token', message)
                self.assertEqual(pub.call_count, 0)  # saved preflight never publishes
            self.assertEqual(len(http.requests), 3)
