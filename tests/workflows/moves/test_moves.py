STAMP = '2026-10-20T12:00:00.123456789012345Z'
DONE = '2026-10-21T12:00:00.123456789012349Z'
NOW = d.instant_from_wire('2026-10-22T12:00:00.123456789012350Z')
CURSOR = d.instant_from_wire('2026-10-20T00:00:00Z')


class MoveRequest:
    def __init__(self, args, outcome='ok'):
        self.args, self.outcome = args, outcome
        self.command = None

    def check(self, request, timeout):
        from urllib.parse import parse_qs
        form = parse_qs(request.data.decode())
        commands = json.loads(form['commands'][0])
        assert len(commands) == 1
        self.command = commands[0]
        assert set(self.command) == {'type', 'uuid', 'args'}
        assert self.command['type'] == 'item_move'
        assert self.command['args'] == self.args
        assert str(UUID(self.command['uuid'])) == self.command['uuid']
        ExpectedRequest('POST', '/sync', 'secret', form={'commands': form['commands'][0]}).check(request, timeout)


