        for phase, fault in (('delivery', OSError('stdout failed')),
                             ('delivery', KeyboardInterrupt()),
                             ('rendering', ValueError('render failed'))):
            with self.subTest(phase=phase, fault=type(fault).__name__):
                # Use a distinct parent each time so every operation is real.
                parent = 'P' if self.store.load_consistent_state().snapshot.items['D'].parent_id != 'P' else 'Q'
                workflow, http = self.workflow(self.after('D', parent, 'cat'),
                                               {'id':'D', 'parent_id':parent})
                workflow.streams = p.OriginalStreams(io.StringIO(), FailingOutput(), io.StringIO())
                target = 'todo_lib.workflows.moves.p.' + ('deliver' if phase == 'delivery' else 'render_move')
                # Exercise actual delivery for OSError, and inject interruption or
                # render faults at their public boundaries.
                from contextlib import nullcontext
                context = nullcontext() if isinstance(fault, OSError) else patch(target, side_effect=fault)
                with context:
                    with self.assertRaises(SyncInterrupted if isinstance(fault, KeyboardInterrupt) else MoveError) as caught:
                        workflow.execute(['move', 'D', parent], deliver=True)
                error = caught.exception.failure if isinstance(caught.exception, SyncInterrupted) else caught.exception
                self.assertEqual(error.remote_outcome, 'accepted')
                self.assertTrue(error.publication_completed)
                self.assertTrue(error.saved_state_available)
                self.assertEqual(error.selected.parent_id, parent)
                self.assertIn('do not replay', str(error).lower())
                self.assertIn('todo --refresh now', str(error))
                self.assertIn('local snapshot publication completed', str(error))
                self.assertNotIn('previous cache was not replaced', str(error))
                with exclusive_lock('after receipt failure', self.root):
                    saved = Synchronizer(None, self.store).read_local()
                    self.assertEqual(saved.snapshot.items['D'].parent_id, parent)
                    self.assertEqual(d.instant_text(saved.snapshot.items['E'].completed_at), DONE)
                self.assertEqual(len(http.requests), 3)

