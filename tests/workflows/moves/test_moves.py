    def boundary(self, steps):
        http = ControlledHTTP([(r, v if isinstance(v, Response) else Response(json.dumps(v).encode()))
                               for r, v in steps])
        self.addCleanup(http.assert_done)
        return Transport('secret', opener=http, sleep=lambda _: None), http

    def sync(self, token, response):
        return ExpectedRequest('POST', '/sync', 'secret', form={
            'sync_token': token, 'resource_types': RESOURCES}), response

    def workflow(self, after=None, args=None, *, outcome='ok', archived=False, omitted=False,
                 active_delta=False, interrupt_at=None):
        saved = self.store.load_consistent_state()
        steps = []
        if args is not None:
            expected = MoveRequest(args, outcome)
            # UUID is generated by production; return operation-attributable proof.
            class Receipt(Response):
                def read(inner, *a):
                    if not getattr(inner, 'filled', False):
                        inner.write(json.dumps({'sync_status': {expected.command['uuid']: outcome}}
                                               if outcome is not None else {}).encode())
                        inner.seek(0)
                        inner.filled = True
                    return super().read(*a)
            source = self.store.load_consistent_state().snapshot.items[args['id']]
            destination_category = (args.get('project_id') or
                self.store.load_consistent_state().snapshot.items[args['parent_id']].category_id)
            token = '*' if destination_category != source.category_id or saved.current_snapshot is None else 'delta-token'
            initial = [r for r in self.rows if r['id'] != 'E'] if active_delta else after
            steps += [(expected, Receipt()), self.sync(token, full(
                projects=self.projects, items=initial, reminders=getattr(self, 'returned_reminders', getattr(self, 'reminders', [])), notes=[n for n in self.notes
                    if not archived or n['item_id'] != 'E']))]
            steps += [self.sync('full-token', delta(items=after) if active_delta else delta())]
            if archived and outcome == 'ok':
                row = deepcopy(next(r for r in self.rows if r['id'] == 'E'))
                row['project_id'] = args.get('project_id', 'cat')
                query = [('since', '2026-10-20T00:00:00Z'),
                         ('until', '2026-10-22T12:00:01Z'), ('limit', '200')]
                for category in (row['project_id'],):
                    steps.append((Expected('/tasks/completed/by_completion_date', [('project_id', category)] + query),
                                  {'items': [row] if category == row['project_id'] and not omitted else []}))
                steps.append((Expected('/comments', [('task_id', 'E'), ('limit', '200')]),
                    {'results': [dict(id='nE', content='own note', posted_at=STAMP,
                                      is_deleted=False, file_attachment=None)], 'next_cursor': None}))
        if interrupt_at is not None:
            class Interrupted(Response):
                def read(self, *args):
                    raise KeyboardInterrupt
            steps = steps[:interrupt_at + 1]
            steps[-1] = (steps[-1][0], Interrupted())
        transport, http = self.boundary(steps)
        return MoveWorkflow(Synchronizer(transport, self.store, clock=lambda: NOW)), http

    def after(self, source, parent, category):
        # Independent fixed fixture membership, not production hierarchy code.
        members = {'A': {'A','B','C','D','E'}, 'B': {'B','C','D','E'},
                   'C': {'C','D','E'}, 'D': {'D','E'}, 'E': {'E'}}[source]
        rows = deepcopy(self.rows)
        for row in rows:
            if row['id'] in members:
                row['project_id'] = category
                if row['id'] == source:
                    row['parent_id'] = parent
        return rows

    def test_deep_category_move_reload_preserves_precision_null_and_every_identity(self):
        old = self.store.load_consistent_state().snapshot
        after = self.after('A', None, 'other')
        workflow, _ = self.workflow([r for r in after if r['id'] != 'E'],
                                   {'id':'A', 'project_id':'other'}, archived=True)
        result = workflow.execute(['move', 'A', 'other'])
        self.assertEqual(result.document.stdout, 'Moved task: A\n  Category: cat -> other')
        saved = self.store.load_consistent_state()
        for snapshot in (saved.snapshot, saved.history.snapshot):
            self.assertEqual(set(snapshot.items), set(old.items))
            self.assertEqual(snapshot.comments, old.comments)
            for identity, before in old.items.items():
                actual = snapshot.items[identity]
                self.assertEqual(actual, replace(before, category_id='other')
                                 if identity in {'A','B','C','D','E'} else before)
                if actual.added_at is not None:
                    self.assertEqual(d.instant_key(actual.added_at), d.instant_key(before.added_at))
                    self.assertEqual(d.instant_text(actual.added_at), d.instant_text(before.added_at))
            self.assertIsNone(snapshot.items['C'].added_at)
            self.assertEqual(d.instant_text(snapshot.items['E'].completed_at), DONE)
        self.assertEqual(saved.cursor, CURSOR)
        for comment in saved.snapshot.comments.values():
            self.assertEqual(d.instant_text(comment.added_at), STAMP)
            self.assertEqual(d.instant_key(comment.added_at), d.instant_key(d.instant_from_wire(STAMP)))

